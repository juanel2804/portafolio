const I18N = (() => {
  const INL = new Set(['B', 'I', 'EM', 'STRONG', 'SMALL', 'SPAN']);
  const leafy = el => [...el.children].every(c => INL.has(c.tagName) && leafy(c));
  const norm = s => s.trim().replace(/\s+/g, ' ');
  let lang = 'es';
  const nodos = [];   // {el, es, en}
  const attrs = [];   // {el, attr, es, en}
  function recolectar(el) {
    if (['SCRIPT', 'STYLE', 'CANVAS', 'svg', 'DIALOG', 'BUTTON'].includes(el.tagName) && el.tagName !== 'BUTTON') return;
    if (el.id === 'typed' || el.id === 'clock' || el.classList.contains('copy') || el.classList.contains('lang-btn')) return;
    const hayTexto = [...el.childNodes].some(n => n.nodeType === 3 && n.textContent.trim());
    if (hayTexto && leafy(el)) {
      const es = norm(el.innerHTML);
      if (EN[es]) nodos.push({ el, es, en: EN[es] });
      return;
    }
    for (const c of el.children) recolectar(c);
  }
  function iniciar() {
    recolectar(document.body);
    document.querySelectorAll('[aria-label],[alt],[title]').forEach(el => {
      ['aria-label', 'alt', 'title'].forEach(a => {
        const v = el.getAttribute(a);
        if (v && ATTR_EN[v]) attrs.push({ el, attr: a, es: v, en: ATTR_EN[v] });
      });
    });
    // texto del botón "copiar"
    const cp = document.querySelector('#copiar .copy');
    if (cp) cp.dataset.es = cp.textContent;
  }
  function aplicar(l) {
    lang = l;
    nodos.forEach(n => n.el.innerHTML = l === 'en' ? n.en : n.es);
    attrs.forEach(a => a.el.setAttribute(a.attr, l === 'en' ? a.en : a.es));
    document.documentElement.lang = l;
    const meta = {
      es: ['Juan Elpidio López García | Ingeniero en Sistemas Computacionales', 'Ingeniero en Sistemas Computacionales. Desarrollo full-stack, IoT en tiempo real, nube en AWS e inteligencia artificial aplicada.'],
      en: ['Juan Elpidio López García | Computer Systems Engineer', 'Computer Systems Engineer. Full-stack development, real-time IoT, AWS cloud and applied artificial intelligence.']
    }[l];
    document.title = meta[0];
    document.querySelector('meta[name=description]')?.setAttribute('content', meta[1]);
    const ty = document.getElementById('typed'); if (ty) ty.textContent = l === 'en' ? ROLES_EN[0] : 'Desarrollo Full-Stack';
    const ck = document.getElementById('clock'); if (ck) ck.textContent = new Date().toLocaleTimeString(l === 'en' ? 'en-US' : 'es-MX', { timeZone: 'America/Mexico_City', hour: '2-digit', minute: '2-digit' });
    const cp = document.querySelector('#copiar .copy'); if (cp) cp.textContent = l === 'en' ? 'copy' : 'copiar';
    const b = document.getElementById('lang-btn');
    if (b) { b.textContent = l === 'en' ? 'ES' : 'EN'; b.setAttribute('aria-label', l === 'en' ? 'Cambiar a español' : 'Switch to English'); b.title = b.getAttribute('aria-label'); }
    try { localStorage.setItem('lang', l); } catch { }
  }
  return {
    get lang() { return lang; },
    iniciar, aplicar,
    alternar() { aplicar(lang === 'en' ? 'es' : 'en'); },
    texto: { copiado: () => lang === 'en' ? 'copied!' : '¡copiado!', copiar: () => lang === 'en' ? 'copy' : 'copiar' },
    roles: es => lang === 'en' ? ROLES_EN : es,
    proy(k, base) {
      if (lang !== 'en' || !PROY_EN[k]) return base;
      const e = PROY_EN[k];
      return {
        ...base, cat: e.cat, titulo: e.titulo, desc: e.desc, puntos: e.puntos,
        tags: e.tags || base.tags,
        fotos: base.fotos.map((f, i) => [f[0], e.fotos?.[i] || f[1]]),
        links: base.links.map((l, i) => [e.links[i] || l[0], l[1], l[2]])
      };
    }
  };
})();
